import { electronAPI as electrontToolkitAPI } from "@electron-toolkit/preload";
import { createLogger } from "@shared/logger";
import type {
	BroadcastEventData,
	OpenClawWeixinLoginMsg,
	ShellWindowFullscreenChange,
	ShortcutActionEvent,
	ShortcutKeyPressEvent,
	ShortcutSyncEvent,
	Tab,
	TabDragGhostClear,
	TabDragGhostHover,
	TabUIState,
	Theme,
} from "@shared/types";
import { contextBridge, ipcRenderer } from "electron";
import "electron-log/preload";
import { SHELL_WINDOW_FULLSCREEN_CHANGED } from "../main/constants";
import { autoGeneratedServices } from "../main/generated/preload-services";
import { getAdditionalArgv, loadDataFromTempFile } from "../main/utils";

const logger = createLogger("preload");

// Increase max listeners to avoid warning when multiple components listen to broadcast events
ipcRenderer.setMaxListeners(25);

const serverPortStr = getAdditionalArgv("server-port");
const serverPort = serverPortStr ? Number.parseInt(serverPortStr, 10) : 8089;
const initialTheme = getAdditionalArgv("theme") ?? null;

const app = {
	platform: process.platform,
	isDev: process.env.NODE_ENV === "development",
	serverPort,
};

const windowId = getAdditionalArgv("window-id") ?? "";

const tabFilePath = getAdditionalArgv("tab-file") ?? "";
const threadFilePath = getAdditionalArgv("thread-file") ?? "";
const messagesFilePath = getAdditionalArgv("messages-file") ?? "";
const codeAgentConfigFilePath = getAdditionalArgv("code-agent-config-file") ?? "";
const claudeCodeAgentStateFilePath = getAdditionalArgv("claude-code-agent-state-file") ?? "";

const tab = loadDataFromTempFile(tabFilePath) ?? {};
const tabs: Tab[] = []; // tabs are managed by tab service, not needed in preload
const thread = loadDataFromTempFile(threadFilePath) ?? {};
const messages = loadDataFromTempFile(messagesFilePath) ?? {};
const codeAgentConfig = loadDataFromTempFile(codeAgentConfigFilePath);
const claudeCodeAgentState = loadDataFromTempFile(claudeCodeAgentStateFilePath);

// Use `contextBridge` APIs to expose Electron APIs to
// renderer only if context isolation is enabled, otherwise
// just add to the DOM global.
if (process.contextIsolated) {
	try {
		contextBridge.exposeInMainWorld("electron", electrontToolkitAPI);
		contextBridge.exposeInMainWorld("electronAPI", {
			theme: {
				setTheme: (theme: Theme) => ipcRenderer.send("app:theme:setTheme", theme),
				onThemeChange: (callback: (theme: Theme) => void) => {
					const listener = (_: unknown, theme: Theme) => callback(theme);
					ipcRenderer.on("app:theme:setTheme", listener);
					return () => ipcRenderer.removeListener("app:theme:setTheme", listener);
				},
				getCurrentTheme: () => ipcRenderer.invoke("app:theme:getCurrentTheme"),
			},
			shortcut: {
				onShortcutSync: (callback: (data: ShortcutSyncEvent) => void) => {
					const listener = (_: unknown, data: ShortcutSyncEvent) => callback(data);
					ipcRenderer.on("shortcut:sync", listener);
					return () => ipcRenderer.removeListener("shortcut:sync", listener);
				},
				onShortcutAction: (callback: (event: ShortcutActionEvent) => void) => {
					const listener = (_: unknown, event: ShortcutActionEvent) => callback(event);
					ipcRenderer.on("shortcut:action", listener);
					return () => ipcRenderer.removeListener("shortcut:action", listener);
				},
				sendShortcutKeyPressed: (event: ShortcutKeyPressEvent) => {
					ipcRenderer.send("shortcut:key-pressed", event);
				},
			},
			onThemeChange: (callback: (theme: string) => void) => {
				const listener = (_: unknown, theme: string) => callback(theme);
				ipcRenderer.on("theme:set", listener);
				return () => ipcRenderer.removeListener("theme:set", listener);
			},
			onThreadListUpdate: (callback: () => void) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "thread-list-updated") {
						callback();
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},

			onThreadBusyStateChanged: (
				callback: (data: { threadId: string; isBusy: boolean }) => void,
			) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "thread-busy-state-changed") {
						callback(eventData.data as { threadId: string; isBusy: boolean });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},

			onScreenshotTriggered: (callback: (data: { threadId: string }) => void) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "trigger-screenshot") {
						callback(eventData.data as { threadId: string });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onShowToast: (
				callback: (data: { type: string; message: string; threadId?: string }) => void,
			) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "show-toast") {
						callback(
							eventData.data as { type: string; message: string; threadId?: string },
						);
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onTriggerSendMessage: (callback: (data: { threadId: string }) => void) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "trigger-send-message") {
						callback(eventData.data as { threadId: string });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onTriggerCreateSkillSummary: (callback: (data: { threadId: string }) => void) => {
				const listener = (_: unknown, data: { threadId: string }) => callback(data);
				ipcRenderer.on("tab:create-skill-summary", listener);
				return () => ipcRenderer.removeListener("tab:create-skill-summary", listener);
			},
			onSidebarStateChanged: (callback: (data: { open: boolean }) => void) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "sidebar-state-changed") {
						callback(eventData.data as { open: boolean });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onSidebarSearchChanged: (callback: (data: { query: string }) => void) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "sidebar-search-changed") {
						callback(eventData.data as { query: string });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onSidebarSearchResultsUpdated: (
				callback: (data: { query: string; resultIds: string[] }) => void,
			) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "sidebar-search-results-updated") {
						callback(eventData.data as { query: string; resultIds: string[] });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onSidebarSearchNavigate: (
				callback: (data: { threadId: string; query: string }) => void,
			) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "sidebar-search-navigate") {
						callback(eventData.data as { threadId: string; query: string });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onApplyDefaultModel: (callback: (data: { model: unknown }) => void) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "apply-default-model") {
						callback(eventData.data as { model: unknown });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onModelsDeleted: (
				callback: (data: { deletedModelIds: string[]; providerId?: string }) => void,
			) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "models-deleted") {
						callback(
							eventData.data as { deletedModelIds: string[]; providerId?: string },
						);
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onShellWindowFullscreenChange: (
				callback: (payload: ShellWindowFullscreenChange) => void,
			) => {
				const listener = (_: unknown, payload: ShellWindowFullscreenChange) =>
					callback(payload);
				ipcRenderer.on(SHELL_WINDOW_FULLSCREEN_CHANGED, listener);
				return () => ipcRenderer.removeListener(SHELL_WINDOW_FULLSCREEN_CHANGED, listener);
			},
			onTabDragGhostHover: (callback: (payload: TabDragGhostHover) => void) => {
				const listener = (_: unknown, payload: TabDragGhostHover) => {
					// Only process if this is the target window
					if (payload.windowId === windowId) {
						callback(payload);
					}
				};
				ipcRenderer.on("tab:drag:ghost:hover", listener);
				return () => ipcRenderer.removeListener("tab:drag:ghost:hover", listener);
			},
			onTabDragGhostClear: (callback: (payload: TabDragGhostClear) => void) => {
				const listener = (_: unknown, payload: TabDragGhostClear) => {
					// Only process if this is the target window
					if (payload.windowId === windowId) {
						callback(payload);
					}
				};
				ipcRenderer.on("tab:drag:ghost:clear", listener);
				return () => ipcRenderer.removeListener("tab:drag:ghost:clear", listener);
			},
			onPersistedStateSync: <T>(key: string, callback: (syncValue: T) => void) => {
				const listener = (_: unknown, syncValue: T) => callback(syncValue);
				ipcRenderer.on(key, listener);
				return () => ipcRenderer.removeListener(key, listener);
			},
			updater: {
				onUpdateChecking: (callback: () => void) => {
					const listener = () => callback();
					ipcRenderer.on("updater:update-checking", listener);
					return () => ipcRenderer.removeListener("updater:update-checking", listener);
				},
				onUpdateAvailable: (callback: () => void) => {
					const listener = () => callback();
					ipcRenderer.on("updater:update-available", listener);
					return () => ipcRenderer.removeListener("updater:update-available", listener);
				},
				onUpdateNotAvailable: (callback: () => void) => {
					const listener = () => callback();
					ipcRenderer.on("updater:update-not-available", listener);
					return () =>
						ipcRenderer.removeListener("updater:update-not-available", listener);
				},
				onUpdateDownloaded: (
					callback: (data: { releaseNotes: string; releaseName: string }) => void,
				) => {
					const listener = (
						_: unknown,
						data: { releaseNotes: string; releaseName: string },
					) => callback(data);
					ipcRenderer.on("updater:update-downloaded", listener);
					return () => ipcRenderer.removeListener("updater:update-downloaded", listener);
				},
				onUpdateError: (callback: (data: { message: string }) => void) => {
					const listener = (_: unknown, data: { message: string }) => callback(data);
					ipcRenderer.on("updater:update-error", listener);
					return () => ipcRenderer.removeListener("updater:update-error", listener);
				},
				onDownloadProgress: (
					callback: (data: {
						percent: number;
						transferred: number;
						total: number;
					}) => void,
				) => {
					const listener = (
						_: unknown,
						data: { percent: number; transferred: number; total: number },
					) => callback(data);
					ipcRenderer.on("updater:download-progress", listener);
					return () => ipcRenderer.removeListener("updater:download-progress", listener);
				},
			},
			...autoGeneratedServices,
			onTabClearMessages: (callback: (data: { tabId: string; threadId: string }) => void) => {
				const listener = (_: unknown, data: { tabId: string; threadId: string }) =>
					callback(data);
				ipcRenderer.on("tab:clear-messages", listener);
				return () => ipcRenderer.removeListener("tab:clear-messages", listener);
			},
			onTabGenerateTitle: (callback: (data: { tabId: string; threadId: string }) => void) => {
				const listener = (_: unknown, data: { tabId: string; threadId: string }) =>
					callback(data);
				ipcRenderer.on("tab:generate-title", listener);
				return () => ipcRenderer.removeListener("tab:generate-title", listener);
			},
			onSandboxCreated: (
				callback: (data: { threadId: string; sandboxId: string }) => void,
			) => {
				const listener = (_: unknown, data: { threadId: string; sandboxId: string }) =>
					callback(data);
				ipcRenderer.on("code-agent:sandbox-created", listener);
				return () => ipcRenderer.removeListener("code-agent:sandbox-created", listener);
			},
			aiApplication: {
				onAiApplicationsLoading: (callback: (loading: boolean) => void) => {
					const listener = (_: unknown, loading: boolean) => callback(loading);
					ipcRenderer.on("ai-applications:loading", listener);
					return () => ipcRenderer.removeListener("ai-applications:loading", listener);
				},
			},
			skill: {
				onSkillImportRequested: (callback: (data: { url: string }) => void) => {
					const listener = (_: unknown, data: { url: string }) => callback(data);
					ipcRenderer.on("skill:import-requested", listener);
					return () => ipcRenderer.removeListener("skill:import-requested", listener);
				},
			},
			onInstallLog: (
				callback: (data: {
					step: string;
					type: "start" | "stdout" | "stderr" | "complete" | "error";
					data: string;
				}) => void,
			) => {
				const listener = (
					_: unknown,
					data: {
						step: string;
						type: "start" | "stdout" | "stderr" | "complete" | "error";
						data: string;
					},
				) => callback(data);
				ipcRenderer.on("install-log", listener);
				return () => ipcRenderer.removeListener("install-log", listener);
			},
			onPodmanHealthCheck: (
				callback: (data: { isOk: boolean; isHealth: boolean; timestamp: number }) => void,
			) => {
				const listener = (
					_: unknown,
					data: { isOk: boolean; isHealth: boolean; timestamp: number },
				) => callback(data);
				ipcRenderer.on("podman-health-check", listener);
				return () => ipcRenderer.removeListener("podman-health-check", listener);
			},
			onLocalSandboxHealthCheck: (
				callback: (data: {
					isOk: boolean;
					isHealth: boolean;
					isOcHealth: boolean;
					error?: string;
					timestamp: number;
				}) => void,
			) => {
				const listener = (
					_: unknown,
					data: {
						isOk: boolean;
						isHealth: boolean;
						isOcHealth: boolean;
						error?: string;
						timestamp: number;
					},
				) => callback(data);
				ipcRenderer.on("local-sandbox-health-check", listener);
				return () => ipcRenderer.removeListener("local-sandbox-health-check", listener);
			},
			onLocalSandboxStateChanged: (
				callback: (data: { starting?: boolean; running?: boolean }) => void,
			) => {
				const listener = (_: unknown, eventData: BroadcastEventData) => {
					if (eventData.broadcastEvent === "local-sandbox-state-changed") {
						callback(eventData.data as { starting?: boolean; running?: boolean });
					}
				};
				ipcRenderer.on("broadcast-event", listener);
				return () => ipcRenderer.removeListener("broadcast-event", listener);
			},
			onWslRestartRequired: (
				callback: (data: { reason: string; message: string }) => void,
			) => {
				const listener = (_: unknown, data: { reason: string; message: string }) =>
					callback(data);
				ipcRenderer.on("wsl-restart-required", listener);
				return () => ipcRenderer.removeListener("wsl-restart-required", listener);
			},
			onTabRequestSnapshot: (callback: () => Promise<TabUIState> | TabUIState) => {
				const listener = async () => {
					try {
						const snapshot = await callback();
						ipcRenderer.send("tab:snapshot-data", snapshot);
					} catch (error) {
						logger.error("Failed to generate snapshot:", error);
						ipcRenderer.send("tab:snapshot-data", null);
					}
				};
				ipcRenderer.on("tab:request-snapshot", listener);
				return () => ipcRenderer.removeListener("tab:request-snapshot", listener);
			},
			openClaw: {
				onWeiXinLoginInformation: (callback: (event: OpenClawWeixinLoginMsg) => void) => {
					const listener = (_: unknown, event: OpenClawWeixinLoginMsg) => callback(event);
					ipcRenderer.on("openclaw-weixin:login", listener);
					return () => ipcRenderer.removeListener("openclaw-weixin:login", listener);
				},
			},
			cloudMode: {
				onTimedBroadcaster: (callback: (data: unknown) => void) => {
					const listener = (_: unknown, data: unknown) => callback(data ?? null);
					ipcRenderer.on("cloud-mode:timed", listener);
					return () => ipcRenderer.removeListener("cloud-mode:timed", listener);
				},
			},
		});

		// Expose shell window ID from process arguments
		contextBridge.exposeInMainWorld("windowId", windowId);
		contextBridge.exposeInMainWorld("tab", tab);
		contextBridge.exposeInMainWorld("tabs", tabs);
		contextBridge.exposeInMainWorld("app", app);
		contextBridge.exposeInMainWorld("thread", thread);
		contextBridge.exposeInMainWorld("messages", messages);
		contextBridge.exposeInMainWorld("codeAgentConfig", codeAgentConfig);
		contextBridge.exposeInMainWorld("claudeCodeAgentState", claudeCodeAgentState);
		contextBridge.exposeInMainWorld("initialTheme", initialTheme);
	} catch (error) {
		logger.error("Preload: Error exposing services", { error });
	}
} else {
	window.app = app;
	window.electron = electrontToolkitAPI;
}
